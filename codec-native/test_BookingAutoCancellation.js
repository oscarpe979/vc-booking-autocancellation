        console.log('▶ Test 73: 50ms event coalescing prevents transient snapshot_incomplete warnings...');
        const s = createFreshSandbox();
        loadMacroWithTestConfig(s);

        const bookingStartTime = new Date(Date.now() - 2 * 60 * 1000).toISOString();
        const bookingEndTime = new Date(Date.now() + 30 * 60 * 1000).toISOString();
        s.xapi.Status.RoomAnalytics.RoomInUse._current = 'False';
        s.xapi.Status.Bookings.Availability.Status._current = 'Free';
        s.xapi.Status.Bookings.Availability.TimeStamp._current = '';
        await s.init();

        // Enable 50ms debounced coalescing
        vm.runInContext('CONFIG.BOOKING_SYNC_COALESCE_DELAY_MS = 50;', s);

        s.xapi.Status.Bookings.Current.Id._current = 'coalesced_booking_id';
        s.xapi.Command.Bookings.Get._response = {
            Booking: {
                Id: 'coalesced_booking_id',
                Time: {
                    StartTime: bookingStartTime,
                    EndTime: bookingEndTime
                }
            }
        };

        // 1. Status event arrives first (T+0ms)
        await s.xapi.Status.Bookings.Availability.Status._listener('BookedUntil');

        assert.ok(findTimeoutWithDelay(50), 'BookedUntil event must schedule a 50ms coalescing timer.');
        assert.strictEqual(s.logEntries.some(entry => entry.args.join(' ').includes('reason=snapshot_incomplete')), false,
            'No warning may be logged while the 50ms coalescing timer is pending.');

        // 2. TimeStamp event arrives 20ms later (T+20ms) before the 50ms timer fires
        await s.xapi.Status.Bookings.Availability.TimeStamp._listener(bookingEndTime);

        // 3. The coalesced 50ms timer fires
        const activeCoalesceTimer = findTimeoutWithDelay(50);
        assert.ok(activeCoalesceTimer, 'Active 50ms coalescing timer must be ready to fire.');
        await activeCoalesceTimer.callback();
        delete activeTimeouts[activeCoalesceTimer.id];

        assert.strictEqual(vm.runInContext('bookingLifecycle.booking.currentBookingEndTime', s), bookingEndTime,
            'Coalesced sync must execute with the arriving timestamp.');
        assert.strictEqual(vm.runInContext('bookingLifecycle.autocancellation.status.status', s), 'Allowed',
            'Coalesced sync must allow the complete short booking.');
        assert.strictEqual(s.logEntries.some(entry => entry.args.join(' ').includes('reason=snapshot_incomplete')), false,
            'Zero snapshot_incomplete warnings should be logged when TimeStamp arrives within the coalescing window.');
        assert.ok(findTimeoutWithDelay(TEST_WARNING_DELAY),
            'Release countdown must be scheduled cleanly in a single pass.');
        console.log('✓ Test 73 Passed.');
