// Helper to look for an active timeout with a specific delay value
function findTimeoutWithDelay(delay) {
    return Object.values(activeTimeouts).find(t => t.delay === delay);
}

// Helper to look for an active timeout by its callback function name
function findTimeoutByCallbackName(name) {
    return Object.values(activeTimeouts).find(t => {
        if (t.callback.name) {
            return t.callback.name === name;
        }
        // Fallback for bound or stringified functions
        const cbStr = t.callback.toString();
        return cbStr.includes('function ' + name) || cbStr.includes(name + '(');
    });
}

