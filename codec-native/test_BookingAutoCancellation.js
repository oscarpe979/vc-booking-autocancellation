async function showRoomUseCheckPrompt() {
    const countdownTimer = findTimeoutWithDelay(TEST_WARNING_DELAY);
    assert.ok(countdownTimer, 'Empty booked room should have an active countdown timer.');

    await countdownTimer.callback();
    delete activeTimeouts[countdownTimer.id];

    const promptExpiryTimer = findTimeoutByCallbackName('releaseBookingAfterPromptExpires');
    assert.ok(promptExpiryTimer, 'Room use check prompt expiry timer should be active after the prompt is displayed.');
    return promptExpiryTimer;
}

